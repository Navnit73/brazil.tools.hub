/** Busca sem acentos e sem diferenciar maiúsculas. */
export function normalize(text: string): string {
  return text.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
}

/** SVG do ícone na cor e no tamanho pedidos, pronto para virar data URL. */
export function iconDataUrl(svg: string, color: string, size: number): string {
  const colored = svg
    .replace(/currentColor/g, color)
    .replace(/width="24"/, `width="${size}"`)
    .replace(/height="24"/, `height="${size}"`)
    .trim();
  return `data:image/svg+xml;base64,${btoa(colored)}`;
}
